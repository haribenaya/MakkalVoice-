export function getLocalizedError(code: AppErrorCode, language: string): string {
  const dict = LOCALIZED_ERRORS[language] ?? EN_ERRORS;
  return dict[code] ?? EN_ERRORS[code];
}

export function resolveLocalizedErrorMessage(
  err: unknown,
  language: string,
  fallbackCode: AppErrorCode = "AI_GENERIC",
): string {
  if (err && typeof err === "object" && "code" in err) {
    const code = (err as { code?: string }).code as AppErrorCode | undefined;
    if (code && code in EN_ERRORS) {
      return getLocalizedError(code, language);
    }
  }
  if (err instanceof Error) {
    const msg = err.message.toLowerCase();
    if (msg.includes("connect") || msg.includes("network") || msg.includes("fetch")) {
      return getLocalizedError("NETWORK_ERROR", language);
    }
    if (msg.includes("timed out") || msg.includes("too long")) {
      return getLocalizedError("AI_TIMEOUT", language);
    }
    if (msg.includes("rate limit") || msg.includes("429")) {
      return getLocalizedError("AI_RATE_LIMIT", language);
    }
    if (msg.includes("busy") || msg.includes("unavailable") || msg.includes("503")) {
      return getLocalizedError("AI_UNAVAILABLE", language);
    }
  }
  return getLocalizedError(fallbackCode, language);
}
